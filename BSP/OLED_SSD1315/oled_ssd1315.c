/* ==================== 图形绘制 ==================== */
 
/**
 * @brief  画直线 (Bresenham算法)
 */
void OLED_DrawLine(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t color)
{
    int16_t dx = (x2 > x1) ? (x2 - x1) : (x1 - x2);
    int16_t dy = (y2 > y1) ? (y2 - y1) : (y1 - y2);
    int16_t sx = (x1 < x2) ? 1 : -1;
    int16_t sy = (y1 < y2) ? 1 : -1;
    int16_t err = dx - dy;
    int16_t x = x1;
    int16_t y = y1;
 
    while (1)
    {
        OLED_SetPixel((uint8_t)x, (uint8_t)y, color);
        if (x == x2 && y == y2) break;
        int16_t e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x += sx; }
        if (e2 < dx)  { err += dx; y += sy; }
    }
}
 
/**
 * @brief  画矩形 (空心)
 */
void OLED_DrawRectangle(uint8_t x1, uint8_t y1, uint8_t x2, uint8_t y2, uint8_t color)
{
    OLED_DrawLine(x1, y1, x2, y1, color);
    OLED_DrawLine(x2, y1, x2, y2, color);
    OLED_DrawLine(x2, y2, x1, y2, color);
    OLED_DrawLine(x1, y2, x1, y1, color);
}
 
