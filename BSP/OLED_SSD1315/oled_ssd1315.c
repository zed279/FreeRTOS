/* ==================== 初始化与控制 ==================== */
 
/**
 * @brief  SSD1315 OLED 初始化
 * @retval 0=成功, 非0=失败
 */
uint8_t OLED_Init(void)
{
    uint8_t ret;
 
    osDelay(100);  /* 上电等待 */
 
    /* 初始化命令序列 */
    ret  = OLED_WriteCmd(SSD1315_CMD_DISPLAY_OFF);          /* 关闭显示 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_CLOCK_DIV);        /* 设置时钟分频 */
    ret |= OLED_WriteCmd(0x80);                             /* 分频因子=1, 振荡器频率=中间值 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_MULTIPLEX);        /* 设置多路复用比 */
    ret |= OLED_WriteCmd(SSD1315_HEIGHT - 1);               /* 64行: 0x3F */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_DISPLAY_OFFSET);   /* 设置显示偏移 */
    ret |= OLED_WriteCmd(0x00);                             /* 偏移=0 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_START_LINE | 0x00);/* 设置起始行=0 */
    ret |= OLED_WriteCmd(SSD1315_CMD_CHARGE_PUMP);          /* 电荷泵设置 */
    ret |= OLED_WriteCmd(SSD1315_CHARGE_PUMP_ENABLE);       /* 开启电荷泵 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_MEM_ADDR_MODE);    /* 设置内存地址模式 */
    ret |= OLED_WriteCmd(SSD1315_ADDR_MODE_HORIZONTAL);     /* 水平地址模式 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SEGMENT_REMAP_127);    /* 段重映射: 列127->SEG0 (水平翻转) */
    ret |= OLED_WriteCmd(SSD1315_CMD_COM_SCAN_REMAP);       /* COM扫描方向: 从下到上 (垂直翻转) */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_COM_PINS);         /* 设置COM引脚配置 */
    ret |= OLED_WriteCmd(0x12);                             /* 0x12: 128x64 配置 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_CONTRAST);         /* 设置对比度 */
    ret |= OLED_WriteCmd(0xCF);                             /* 对比度值 */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_PRECHARGE);        /* 设置预充电周期 */
    ret |= OLED_WriteCmd(0xF1);                             /* 预充电: Phase1=1, Phase2=F */
    ret |= OLED_WriteCmd(SSD1315_CMD_SET_VCOMH);            /* 设置VCOMH电压 */
    ret |= OLED_WriteCmd(0x30);                             /* VCOMH = 0.83*VCC */
    ret |= OLED_WriteCmd(SSD1315_CMD_ENTIRE_DISPLAY_OFF);   /* 全局显示关闭 (跟随RAM) */
    ret |= OLED_WriteCmd(SSD1315_CMD_NORMAL_DISPLAY);       /* 正常显示模式 */
    ret |= OLED_WriteCmd(SSD1315_CMD_DISPLAY_ON);           /* 开启显示 */
 
    if (ret != 0)
        return 1;
 
    /* 只清显存 (RAM), 不推屏 —— 这里以前是 OLED_Clear():
     * 它清完 RAM 会立刻把 8 页全推一遍, 软件 IIC 下约 150ms, 而屏幕内容马上
     * 就会被调用方的第一帧覆盖 (oled_task: OledTask_StaticScreen() 后的 OLED_Update()),
     * 等于开机白等 150ms。
     *
     * 清完 DirtyMask = 0xFF, 保证调用方第一次 OLED_Update() 是全屏刷新。
     * "第一帧必须推满 8 页"这条不能省 —— SSD1315 上电时片内 RAM 是随机值,
     * 本函数下发的命令序列只是让它开始跟随 RAM 显示, 并没有清屏能力 ——
     * 只是不该在这里推完、再被同样的内容推第二遍。 */
    OLED_ClearBuffer();
    return 0;
}
 
