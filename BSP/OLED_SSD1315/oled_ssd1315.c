/* ==================== 显存缓冲区 ==================== */
static uint8_t OLED_GRAM[SSD1315_PAGES][SSD1315_WIDTH];

/* 脏页标记: bit N = 第 N 页自上次刷新后被改动过。
 * 软件 IIC 推一整帧 (8 页 x 128B) 约 150ms, 全屏刷新最高只有 6~7Hz;
 * 有脏页标记后 OLED_Update() 只推真正变化的页 (实测约 19ms/页)。 */
static uint8_t OLED_DirtyMask = 0x00;

static inline void OLED_MarkDirty(uint8_t page)
{
    OLED_DirtyMask |= (uint8_t)(1u << page);
}
 
/* ==================== 底层I2C操作 ==================== */
/* 注意: SSD1315_I2C_ADDR = 0x78 (8位写地址, 已含R/W位=0).
 *        iic_send_byte 直接发送字节, 不做左移, 因此仍传 0x78.
 *        若改用 iic_master_write API, 需传 7 位地址 0x3C. */
 
/**
 * @brief  向SSD1315写入一个命令
 * @param  cmd: 命令字节
 * @retval 0=成功, 非0=失败
 */
static uint8_t OLED_WriteCmd(uint8_t cmd)
{
    iic_status_t ret;
    iic_start(IIC_BUS_OLED);
    ret = iic_send_byte(IIC_BUS_OLED, SSD1315_I2C_ADDR);  /* 设备地址 + 写 */
    if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 1; }
    ret = iic_send_byte(IIC_BUS_OLED, 0x00);              /* 控制字节: Co=0, D/C#=0 (命令) */
    if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 2; }
    ret = iic_send_byte(IIC_BUS_OLED, cmd);               /* 命令字节 */
    if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 3; }
    iic_stop(IIC_BUS_OLED);
    return 0;
}
 
/* 说明: 模板原有的 OLED_WriteData() (单字节写) 已在工程副本中删除 ——
 * 它没有任何调用者, 功能完全被 OLED_WriteDataBurst() 覆盖,
 * 保留只会产生 AC5 的 #177-D "declared but never referenced" 警告。
 * 需要写单字节时用 OLED_WriteDataBurst(&b, 1) 即可。 */
 
/**
 * @brief  向SSD1315连续写入多个数据字节
 * @param  pdata: 数据缓冲区指针
 * @param  len: 数据长度
 * @retval 0=成功, 非0=失败
 */
static uint8_t OLED_WriteDataBurst(const uint8_t *pdata, uint16_t len)
{
    iic_status_t ret;
    iic_start(IIC_BUS_OLED);
    ret = iic_send_byte(IIC_BUS_OLED, SSD1315_I2C_ADDR);
    if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 1; }
    ret = iic_send_byte(IIC_BUS_OLED, 0x40);              /* 控制字节: 数据模式 */
    if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 2; }
    for (uint16_t i = 0; i < len; i++)
    {
        ret = iic_send_byte(IIC_BUS_OLED, pdata[i]);
        if (ret != IIC_OK) { iic_stop(IIC_BUS_OLED); return 3; }
    }
    iic_stop(IIC_BUS_OLED);
    return 0;
}
 
